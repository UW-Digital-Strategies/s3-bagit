"""Render the static bash completion script from the argparse parser.

``completions/s3-bagit.bash`` is this module's output, committed, and the
wheel installs it under ``share/bash-completion/completions/`` so bash's
on-demand loader finds it beside the ``uv tool install`` symlink with no
profile edit. A static script rather than ``argcomplete``:
the words are fixed, so Tab never has to start Python.

What it completes: subcommand names, each subcommand's options, and the
top-level options. What it does not: positionals, which are all S3 URLs or
free text, and the value after a value-taking option. Neither falls back
to filename completion, because no argument names a local path.

``make completions`` regenerates the file; ``tests/test_completion.py``
fails when it has drifted from the parser.

Every name is ``_``-prefixed for the same reason as ``_cli_parsers.py``.
"""

import argparse
import sys

from s3_bagit._cli_parsers import _build_parser

_HEADER = """\
# bash completion for s3-bagit.
# Generated by `make completions` from the argparse parser
# (src/s3_bagit/_completion.py). Do not edit by hand.
"""


def _option_strings(parser: argparse.ArgumentParser) -> list[str]:
    return [opt for action in parser._actions for opt in action.option_strings]


def _valued_option_strings(parser: argparse.ArgumentParser) -> list[str]:
    """Options that consume the next word as their value."""
    return [opt for action in parser._actions if action.nargs != 0 for opt in action.option_strings]


def _subcommands(parser: argparse.ArgumentParser) -> dict[str, argparse.ArgumentParser]:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return dict(action.choices)
    raise ValueError(f"{parser.prog} has no subcommands to complete")


def _render(parser: argparse.ArgumentParser) -> str:
    """Return the bash completion script for *parser*.

    Raises:
        ValueError: if *parser* has no subcommands, or if a top-level
            option takes a value. The script finds the subcommand as the
            first word that is not an option, which is only right while
            no top-level option consumes the word after it.
    """
    top_valued = _valued_option_strings(parser)
    if top_valued:
        raise ValueError(
            f"top-level option(s) {', '.join(top_valued)} take a value; the "
            "generated script would mistake that value for the subcommand"
        )
    subs = _subcommands(parser)
    names = " ".join(subs)
    cases = [f'        "") opts="{" ".join(_option_strings(parser))}" ;;']
    for name, sub in subs.items():
        valued = " ".join(_valued_option_strings(sub))
        cases.append(
            f'        {name}) opts="{" ".join(_option_strings(sub))}"; valued="{valued}" ;;'
        )
    case_block = "\n".join(cases)
    return f"""{_HEADER}
_s3_bagit() {{
    local cur prev cmd="" opts="" valued="" i
    cur="${{COMP_WORDS[COMP_CWORD]}}"
    prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    for ((i = 1; i < COMP_CWORD; i++)); do
        if [[ "${{COMP_WORDS[i]}}" != -* ]]; then
            cmd="${{COMP_WORDS[i]}}"
            break
        fi
    done
    case "$cmd" in
{case_block}
        *) return 0 ;;
    esac
    if [[ -n "$valued" && " $valued " == *" $prev "* ]]; then
        return 0
    fi
    if [[ "$cur" == -* ]]; then
        mapfile -t COMPREPLY < <(compgen -W "$opts" -- "$cur")
    elif [[ -z "$cmd" ]]; then
        mapfile -t COMPREPLY < <(compgen -W "{names}" -- "$cur")
    fi
    return 0
}}
complete -F _s3_bagit s3-bagit
"""


if __name__ == "__main__":
    sys.stdout.write(_render(_build_parser()))
